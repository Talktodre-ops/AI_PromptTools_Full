-- Add new columns to existing prompt-gallery table
ALTER TABLE public."prompt-gallery"
ADD COLUMN IF NOT EXISTS views INTEGER DEFAULT 0,
ADD COLUMN IF NOT EXISTS likes INTEGER DEFAULT 0,
ADD COLUMN IF NOT EXISTS rating NUMERIC(3,2) DEFAULT 0.0 CHECK (rating >= 0 AND rating <= 5),
ADD COLUMN IF NOT EXISTS rating_count INTEGER DEFAULT 0,
ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW();

-- Create indexes for performance
CREATE INDEX IF NOT EXISTS idx_prompt_gallery_views ON public."prompt-gallery"(views DESC);
CREATE INDEX IF NOT EXISTS idx_prompt_gallery_likes ON public."prompt-gallery"(likes DESC);
CREATE INDEX IF NOT EXISTS idx_prompt_gallery_rating ON public."prompt-gallery"(rating DESC);
CREATE INDEX IF NOT EXISTS idx_prompt_gallery_created_at ON public."prompt-gallery"(created_at DESC);

-- Create a trigger to automatically update the updated_at timestamp
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ language 'plpgsql';

-- Apply the trigger to the prompt-gallery table
DROP TRIGGER IF EXISTS update_prompt_gallery_updated_at ON public."prompt-gallery";
CREATE TRIGGER update_prompt_gallery_updated_at
    BEFORE UPDATE ON public."prompt-gallery"
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- Create table for user favorites (many-to-many relationship)
CREATE TABLE IF NOT EXISTS public."user-favorites" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL, -- You can link this to auth.users if you have authentication
    prompt_id BIGINT NOT NULL REFERENCES public."prompt-gallery"(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE(user_id, prompt_id) -- Prevent duplicate favorites
);

-- Create indexes for user favorites
CREATE INDEX IF NOT EXISTS idx_user_favorites_user_id ON public."user-favorites"(user_id);
CREATE INDEX IF NOT EXISTS idx_user_favorites_prompt_id ON public."user-favorites"(prompt_id);

-- Create a view to get prompts with aggregated stats
CREATE OR REPLACE VIEW public."prompt-gallery-with-stats" AS
SELECT
    pg.*,
    COALESCE(fav_count.count, 0) as favorite_count
FROM public."prompt-gallery" pg
LEFT JOIN (
    SELECT prompt_id, COUNT(*) as count
    FROM public."user-favorites"
    GROUP BY prompt_id
) fav_count ON pg.id = fav_count.prompt_id;

-- Function to increment views
CREATE OR REPLACE FUNCTION increment_prompt_views(prompt_id BIGINT)
RETURNS VOID AS $$
BEGIN
    UPDATE public."prompt-gallery"
    SET views = views + 1, updated_at = NOW()
    WHERE id = prompt_id;
END;
$$ LANGUAGE plpgsql;

-- Function to toggle favorite
CREATE OR REPLACE FUNCTION toggle_prompt_favorite(user_id UUID, prompt_id BIGINT)
RETURNS BOOLEAN AS $$
DECLARE
    is_favorited BOOLEAN;
BEGIN
    -- Check if already favorited
    SELECT EXISTS(
        SELECT 1 FROM public."user-favorites"
        WHERE user_id = toggle_prompt_favorite.user_id
        AND prompt_id = toggle_prompt_favorite.prompt_id
    ) INTO is_favorited;

    IF is_favorited THEN
        -- Remove favorite
        DELETE FROM public."user-favorites"
        WHERE user_id = toggle_prompt_favorite.user_id
        AND prompt_id = toggle_prompt_favorite.prompt_id;

        -- Decrement likes counter
        UPDATE public."prompt-gallery"
        SET likes = GREATEST(likes - 1, 0), updated_at = NOW()
        WHERE id = toggle_prompt_favorite.prompt_id;

        RETURN FALSE;
    ELSE
        -- Add favorite
        INSERT INTO public."user-favorites" (user_id, prompt_id)
        VALUES (toggle_prompt_favorite.user_id, toggle_prompt_favorite.prompt_id);

        -- Increment likes counter
        UPDATE public."prompt-gallery"
        SET likes = likes + 1, updated_at = NOW()
        WHERE id = toggle_prompt_favorite.prompt_id;

        RETURN TRUE;
    END IF;
END;
$$ LANGUAGE plpgsql;

-- Update existing rows to have default values
UPDATE public."prompt-gallery"
SET
    views = COALESCE(views, 0),
    likes = COALESCE(likes, 0),
    rating = COALESCE(rating, 0.0),
    rating_count = COALESCE(rating_count, 0),
    created_at = COALESCE(created_at, NOW()),
    updated_at = COALESCE(updated_at, NOW())
WHERE views IS NULL OR likes IS NULL OR rating IS NULL OR rating_count IS NULL OR created_at IS NULL OR updated_at IS NULL;

-- Populate all prompts with realistic random data
UPDATE public."prompt-gallery"
SET
    -- Views: Random between 100-5000 views per prompt
    views = (RANDOM() * 4900)::INTEGER + 100,

    -- Likes: Random between 5-500 likes (roughly 5-15% of views)
    likes = (RANDOM() * 495)::INTEGER + 5,

    -- Rating: Random between 3.5-5.0 (realistic ratings, mostly positive)
    rating = ROUND((RANDOM() * 1.5 + 3.5)::NUMERIC, 2),

    -- Rating count: Random between 20-300 people who rated
    rating_count = (RANDOM() * 280)::INTEGER + 20,

    -- Created at: Random dates within last 6 months
    created_at = NOW() - (RANDOM() * INTERVAL '180 days'),

    updated_at = NOW()
WHERE id IS NOT NULL;

-- Update updated_at to be slightly after created_at for realism
UPDATE public."prompt-gallery"
SET updated_at = created_at + (RANDOM() * INTERVAL '30 days')
WHERE updated_at = created_at;

COMMENT ON TABLE public."prompt-gallery" IS 'Updated gallery table with views, likes, and timestamps';
COMMENT ON COLUMN public."prompt-gallery".views IS 'Number of times this prompt has been viewed/opened';
COMMENT ON COLUMN public."prompt-gallery".likes IS 'Number of users who favorited this prompt';
COMMENT ON TABLE public."user-favorites" IS 'User favorites for prompts (many-to-many)';

